/// SplitMix64 — mixes raw entropy into well-distributed 64-bit values so
/// each retry round below lands on different indices.
fn mix_entropy(mut x: u64) -> u64 {
    x = x.wrapping_add(0x9E37_79B9_7F4A_7C15);
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

/// Deterministically maps entropy to an alias so tests can exercise the
/// guards directly. Guarantees: non-empty halves, never the same entry on
/// both sides ("Goku-Goku"), and length within MAX_ALIAS_CHARS.
fn name_from_entropy(first_seed: u64, second_seed: u64) -> String {
    for attempt in 0u64..16 {
        let first_index =
            (mix_entropy(first_seed.wrapping_add(attempt)) as usize) % FIRST_PARTS.len();
        let second_index =
            (mix_entropy(second_seed.wrapping_add(attempt)) as usize) % SECOND_PARTS.len();
        let first = FIRST_PARTS[first_index];
        let mut second = SECOND_PARTS[second_index];
        if second == first {
            // Same word on both sides reads silly — step to the neighbour.
            second = SECOND_PARTS[(second_index + 1) % SECOND_PARTS.len()];
        }
        let name = format!("{first}-{second}");
        if name.chars().count() <= MAX_ALIAS_CHARS {
            return name;
        }
        eprintln!("generated alias exceeds {MAX_ALIAS_CHARS} chars, retrying: {name}");
    }
    // Practically unreachable (pool entries are size-tested below); fall
    // back to a linear scan for any valid pair rather than emit a bad alias.
    for &first in FIRST_PARTS {
        for &second in SECOND_PARTS {
            if second != first {
                let name = format!("{first}-{second}");
                if name.chars().count() <= MAX_ALIAS_CHARS {
                    return name;
                }
            }
        }
    }
    unreachable!("name pools contain no valid combination");
}

pub fn generate_anime_name() -> String {
    // A v4 UUID carries ~122 bits of OS randomness. The old version hashed
    // the wall clock, so two calls within one clock tick could produce
    // identical names (e.g. tapping the randomize button twice fast).
    let bytes = *uuid::Uuid::new_v4().as_bytes();
    let first_seed = u64::from_le_bytes(bytes[..8].try_into().expect("uuid half is 8 bytes"));
    let second_seed = u64::from_le_bytes(bytes[8..].try_into().expect("uuid half is 8 bytes"));
    name_from_entropy(first_seed, second_seed)
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            alias: generate_anime_name(),
            port: 3030,
            device_id: uuid::Uuid::new_v4().to_string(),
            receiving_enabled: true,
            download_dir: None,
        }
    }
}

fn is_old_style_name(name: &str) -> bool {
    // Old names crate generates names like "narrow-cows", "brave-tiger" etc.
    // They're lowercase with a hyphen. Our anime names are proper case.
    name.contains('-') && name.chars().all(|c| c.is_lowercase() || c == '-')
}

pub fn load_config(app: &AppHandle) -> AppConfig {
    // app_config_dir() is part of the path manager in Tauri
    let config_path_res = app.path().app_config_dir();

    if let Ok(config_dir) = config_path_res {
        let config_path = config_dir.join("settings.json");
        if config_path.exists() {
            if let Ok(content) = fs::read_to_string(&config_path) {
                let parsed = serde_json::from_str::<AppConfig>(&content);
                if parsed.is_err() {
                    // Don't silently throw away a file we merely failed to
                    // parse: keep it next to the fresh defaults.
                    let backup = config_dir.join("settings.json.bak");
                    eprintln!("settings.json is unreadable; backing up to {:?}", backup);
                    let _ = fs::copy(&config_path, backup);
                }
                if let Ok(mut config) = parsed {
                    if config.port < MIN_PORT {
                        config.port = 3030;
                    }
                    // If the name looks like it came from the old generator, regenerate it
                    let mut dirty = false;
                    if is_old_style_name(&config.alias) {
                        config.alias = generate_anime_name();
                        dirty = true;
                    }
                    // Settings files from before discovery v2 have no identity.
                    if config.device_id.trim().is_empty() {
                        config.device_id = uuid::Uuid::new_v4().to_string();
                        dirty = true;
                    }
                    if dirty {
                        let _ = save_config(app, &config);
                    }
                    return config;
                }
            }
        }
    }

    let config = AppConfig::default();
    // Try to save the default config immediately
    let _ = save_config(app, &config);
    config
}

pub fn save_config(app: &AppHandle, config: &AppConfig) -> Result<(), String> {
    let config_dir = app.path().app_config_dir().map_err(|e| e.to_string())?;

    if !config_dir.exists() {
        fs::create_dir_all(&config_dir).map_err(|e| e.to_string())?;
    }

    let config_path = config_dir.join("settings.json");
    let content = serde_json::to_string_pretty(config).map_err(|e| e.to_string())?;
    // Write-then-rename so a crash mid-save can't leave a truncated file.
    let tmp_path = config_dir.join("settings.json.tmp");
    fs::write(&tmp_path, content).map_err(|e| e.to_string())?;
    fs::rename(&tmp_path, &config_path).map_err(|e| e.to_string())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pools_have_no_duplicates() {
        for (label, pool) in [("first", FIRST_PARTS), ("second", SECOND_PARTS)] {
            let mut seen = std::collections::HashSet::new();
            for entry in pool {
                assert!(seen.insert(*entry), "duplicate {entry:?} in {label} pool");
            }
        }
    }

    #[test]
    fn pool_entries_are_reasonably_sized() {
        for pool in [FIRST_PARTS, SECOND_PARTS] {
            for entry in pool {
                let len = entry.chars().count();
                assert!(
                    (1..=24).contains(&len),
                    "pool entry {entry:?} has odd length {len}"
                );
            }
        }
    }

    #[test]
    fn names_never_repeat_a_part_and_respect_the_limit() {
        // Degenerate seeds that would collide under the old time-based hash.
        let mut seeds = vec![(0u64, 0u64), (u64::MAX, u64::MAX), (0, u64::MAX)];
        for n in 0..500u64 {
            seeds.push((n, n.wrapping_mul(0x517C_C1B7_2722_0A95)));
        }
        for (a, b) in seeds {
            let name = name_from_entropy(a, b);
            let (first, second) = name.split_once('-').expect("alias contains a hyphen");
            assert!(!first.is_empty() && !second.is_empty());
            assert_ne!(first, second, "both halves equal for entropy ({a}, {b})");
            assert!(
                name.chars().count() <= MAX_ALIAS_CHARS,
                "alias too long: {name}"
            );
        }
    }

    #[test]
    fn generation_is_varied() {
        let mut unique = std::collections::HashSet::new();
        for _ in 0..1000 {
            let name = generate_anime_name();
            assert!(name.chars().count() <= MAX_ALIAS_CHARS, "too long: {name}");
            unique.insert(name);
        }
        assert!(
            unique.len() > 600,
            "generator collapsed to {} unique names",
            unique.len()
        );
    }
}
